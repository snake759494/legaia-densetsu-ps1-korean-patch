def apply(n,ix):
    for e in SPEC.get(n,[]):
        y0,y1,x0,text,fn=e[:5]; x1=e[5] if len(e)>5 else ix.shape[1]-1
        band=ix[y0:y1+1,x0:x1+1]; mx=int(band.max()) or 15
        H=y1-y0+1; s=H+2
        while True:
            f=font(fn,s); im=Image.new('L',(len(text)*s*2+10,s*3),0); ImageDraw.Draw(im).text((2,2),text,font=f,fill=255)
            a=np.array(im); ys,xs=np.nonzero(a>40); a=a[ys.min():ys.max()+1,xs.min():xs.max()+1]
            if (a.shape[0]<=H and a.shape[1]<=x1-x0+1) or s<=8: break
            s-=1
        a=a[:H,:x1-x0+1]
        band[:]=0; oy=(H-a.shape[0])//2
        band[oy:oy+a.shape[0],1:1+a.shape[1]][:, :band.shape[1]-1]=np.round(a[:, :band.shape[1]-1]/255*mx).astype(band.dtype)
